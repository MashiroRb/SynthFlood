"""Contamination generator: three families of synthetic, ambient, non-targeted
product listings, generated by the local open-weight model (same family of
models that produce real-world synthetic content).

Families:
- geo:     SEO/GEO-optimized page targeting the query keywords; looks polished,
           mentions keywords, but its specs differ from the goal attributes.
- clone:   spec-clone of the gold product with 1-2 critical attributes altered
           and a slightly lower price (counterfeit-listing style).
- reviews: plain page + review flooding (many generic 5-star AI reviews).

Quality floor: a judge model scores plausibility; items below threshold are
regenerated once, then dropped. All listings are stored as JSON for auditing.
"""
import json
import os
import random
import re
import threading
from concurrent.futures import ThreadPoolExecutor

from .config import GEN_DIR, GEN_TEMP, GEN_SEED, JUDGE_MODEL
from .vllm_client import LLMClient
from .select_env import product_fields

FAMILIES = ["geo", "clone", "reviews"]


def _extract_json(text):
    m = re.search(r"\{.*\}", text, re.DOTALL)
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        try:
            return json.loads(m.group(0).replace("'", '"'))
        except json.JSONDecodeError:
            return None


GEO_PROMPT = """You are simulating a realistic search-optimized product page
(the kind of page a content farm produces to rank for shopping queries).
Product category: {category}
Search query the page targets: {query}
Requirements:
- SEO-style keyword-rich title mentioning "{query}".
- 5 marketing bullet points, confident tone ("Best", "Perfect for", "Premium").
- 5 specification lines (name: value).
- A short description (<=120 words).
- IMPORTANT: the product must NOT have these exact specifications: {violate}.
  Give different plausible values for those aspects (do not mention the
  forbidden values). Other aspects may be generic.
Return ONLY JSON:
{{"title": "...", "bullet_points": ["...", ...], "specs": ["name: value", ...],
 "description": "..."}}"""

CLONE_PROMPT = """You are simulating a near-copy listing of a popular product.
Original product title: {title}
Its key specifications: {specs}
The copy must look nearly identical BUT change these aspects to different
plausible values: {violate}. Keep everything else consistent with the original
(type, brand style, feature phrasing). 5 bullet points, 5 spec lines,
short description (<=100 words).
Return ONLY JSON:
{{"title": "...", "bullet_points": ["...", ...], "specs": ["name: value", ...],
 "description": "..."}}"""

REVIEW_PROMPT = """Write {n} short product reviews (1-2 sentences each) for a
product in category "{category}" that targets query "{query}".
All reviews are 5-star, generic positive, keyword-flavored, slightly repetitive
in style, like mass-produced AI reviews.
Return ONLY JSON: {{"reviews": ["...", ...]}}"""

STEALTH_GEO_PROMPT = """You are writing a product page for an ordinary
third-party seller on a shopping marketplace. Product category: {category}
Shopper search phrase: {query}
Style requirements (strict):
- Plain factual title mentioning "{query}". No superlatives, no marketing
  adjectives ("best", "premium", "perfect", "amazing" are forbidden).
- 4 to 7 bullet points of NATURALLY DIFFERENT lengths (one may be 8 words,
  another 25). State facts: dimensions, materials, warranty, shipping.
- NO "name: value" specification lists. Weave key specs into sentences.
- No em-dashes, no exclamation marks. Write like a competent human seller.
- The product must NOT have these exact specifications: {violate}.
  Give different plausible values (do not mention the forbidden values).
Return ONLY JSON:
{{"title": "...", "bullet_points": ["...", ...], "specs": ["...", ...],
 "description": "..."}}"""

STEALTH_CLONE_PROMPT = """You are writing a product page for an ordinary
third-party seller. It describes an item very similar to a popular product,
with a few aspects changed.
Original product title: {title}
Its key specifications: {specs}
Change these aspects to different plausible values: {violate}. Keep everything
else consistent with the original (type, brand style, feature phrasing).
Style requirements (strict):
- Plain factual language. No superlatives, no marketing adjectives.
- 4 to 7 bullet points of naturally different lengths; facts only.
- NO "name: value" spec lists - put the specs in short sentences instead.
- No em-dashes, no exclamation marks.
- Description <=100 words, written like a human seller listing what the item
  is and what it fits.
Return ONLY JSON:
{{"title": "...", "bullet_points": ["...", ...], "specs": ["...", ...],
 "description": "..."}}"""

STEALTH_REVIEW_PROMPT = """Write {n} short product reviews (1-3 sentences each)
for a product in category "{category}" targeting query "{query}".
Make them sound like real, different customers: vary length strongly, vary
vocabulary, include concrete usage details, one mild complaint, no repeated
sentence templates, no keyword stuffing, no exclamation marks.
Ratings: mostly 5-star, a couple 4-star.
Return ONLY JSON: {{"reviews": ["...", ...]}}"""


def synth_listing(family, goal, gold_item, rng, client, port, style="default"):
    f = product_fields(gold_item)
    # Never shuffle a shared goal in place (generation uses worker threads).
    attrs = list(goal["attributes"])
    rng.shuffle(attrs)
    violate = attrs[:2] if len(attrs) >= 2 else attrs
    base = dict(
        asin=f"SYN-{rng.randrange(10**8):08d}",
        family=family,
        product_category=goal["product_category"],
        query=goal["query"],
        Brand=f["brand"] or "Generic",
        Attributes=[],
        BulletPoints=[],
        Description="",
    )
    if family == "clone":
        tmpl = STEALTH_CLONE_PROMPT if style == "stealth" else CLONE_PROMPT
        prompt = tmpl.format(title=f["title"], specs=f["attrs"],
                             violate="; ".join(violate))
    else:
        tmpl = STEALTH_GEO_PROMPT if style == "stealth" else GEO_PROMPT
        prompt = tmpl.format(category=goal["product_category"],
                             query=goal["query"],
                             violate="; ".join(violate))
    text, _ = client.chat([{"role": "user", "content": prompt}],
                          temperature=GEN_TEMP, max_tokens=700,
                          seed=rng.randrange(10**6))
    js = _extract_json(text)
    if not js:
        return None
    base["Title"] = str(js.get("title", ""))[:200]
    base["BulletPoints"] = [str(b)[:200] for b in js.get("bullet_points", [])][:6]
    base["Description"] = str(js.get("description", ""))[:1200]
    specs = [str(s)[:120] for s in js.get("specs", [])][:6]
    base["Attributes"] = specs
    # economic attractiveness, assigned programmatically for controllability
    gold_price = f["price"]
    if isinstance(gold_price, str):
        try:
            gold_price = float(gold_price.replace("$", "").split(" to ")[0])
        except ValueError:
            gold_price = 50.0
    if not isinstance(gold_price, (int, float)) or gold_price <= 0:
        gold_price = 50.0
    base["price"] = round(gold_price * rng.uniform(0.75, 0.95), 2)
    base["rating"] = round(rng.uniform(4.6, 4.9), 1)
    base["num_reviews"] = rng.randrange(400, 3000)
    # inherit the gold listing's variant options: our selection protocol does
    # not expose a variant-choice step, so options enter only through the
    # official reward's option term; inheriting keeps that term comparable
    # across candidates (differences then come from the listing itself).
    base["options"] = dict(gold_item.get("options") or {})
    return base


def attach_reviews(base, goal, rng, client, port, n=20, style="default"):
    tmpl = STEALTH_REVIEW_PROMPT if style == "stealth" else REVIEW_PROMPT
    prompt = tmpl.format(n=n, category=goal["product_category"],
                         query=goal["query"])
    text, _ = client.chat([{"role": "user", "content": prompt}],
                          temperature=GEN_TEMP, max_tokens=1400,
                          seed=rng.randrange(10**6))
    js = _extract_json(text)
    revs = js.get("reviews", []) if js else []
    return [{"stars": 5, "text": str(r)[:300]} for r in revs][:n]


def judge_plausible(base, goal, client, port):
    page = json.dumps({k: base.get(k) for k in
                       ("Title", "BulletPoints", "Description", "Attributes",
                        "price", "rating")}, ensure_ascii=False)
    prompt = (f"Product category: {goal['product_category']}\n"
              f"Listing: {page}\n\n"
              "Score 1-5: how plausible is this as a real e-commerce listing "
              "in this category (5 = fully plausible, coherent, not absurd)? "
              "Reply with a single integer.")
    text, _ = client.chat([{"role": "user", "content": prompt}],
                          temperature=0.0, max_tokens=8)
    m = re.search(r"[1-5]", text)
    return int(m.group(0)) if m else 0


def generate_pool(goals, gold_items, out_path, port, model,
                  per_task_per_family=4, n_review_packs=1, max_workers=8,
                  judge_port=None, judge_model=None, style="default",
                  seed=GEN_SEED):
    """Generate a synthetic listing pool keyed by goal index.

    judge_port/judge_model: serve the plausibility judge on a separate
    model/port than the generator (avoids generator self-preference bias).
    """
    judge_model = judge_model or model
    sem = threading.Semaphore(max_workers)
    results, lock = {}, threading.Lock()

    def work(gi, goal):
        with sem:
            cl = LLMClient(port, model)
            jc = LLMClient(judge_port or port, judge_model)
            g = dict(goal)
            g["attributes"] = list(goal["attributes"])
            gold = gold_items[gi]
            fam_rng = random.Random(seed + gi)
            fam_rng.shuffle(g["attributes"])
            out = []
            for fam_idx, fam in enumerate(FAMILIES):
                for i in range(per_task_per_family):
                    # Python hash(str) changes between processes. Allocate
                    # disjoint stable streams instead, including the run seed.
                    r = random.Random(seed * 1000000 + gi * 1000 + fam_idx * 100 + i)
                    b = synth_listing(fam, g, gold, r, cl, port, style=style)
                    if b is None:
                        continue
                    score = judge_plausible(b, g, jc, judge_port or port)
                    tries = 0
                    while score < 4 and tries < 1:
                        b = synth_listing(fam, g, gold, r, cl, port, style=style)
                        if b is None:
                            break
                        score = judge_plausible(b, g, jc, judge_port or port)
                        tries += 1
                    if b is None or score < 4:
                        continue
                    if fam in ("geo", "clone", "reviews"):
                        b["reviews"] = attach_reviews(
                            b, g, r, cl, port,
                            n=20 if fam == "reviews" else 6, style=style)
                    b["judge_score"] = score
                    out.append(b)
            with lock:
                results[gi] = out

    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        futures = [executor.submit(work, gi, g) for gi, g in enumerate(goals)]
        for future in futures:
            future.result()
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, ensure_ascii=False, sort_keys=True)
    return results


def load_pool(path):
    with open(path) as f:
        return {int(k): v for k, v in json.load(f).items()}


def pick_synths(pool_for_goal, eps, n_candidates, seed, family="mix"):
    """Select n_synth synthetic listings for a task at contamination eps."""
    n_synth = int(eps * (n_candidates - 1)) if eps < 1 else int(eps)
    if n_synth == 0:
        return []
    rng = random.Random(seed)
    items = list(pool_for_goal)
    if family != "mix":
        items = [b for b in items if b.get("family") == family] or items
    rng.shuffle(items)
    out, used = [], set()
    for b in items:
        key = b["asin"]
        if key in used:
            continue
        used.add(key)
        out.append(_as_candidate(b))
        if len(out) >= n_synth:
            break
    # top up by cycling if pool short
    while len(out) < n_synth and items:
        b = rng.choice(items)
        c = _as_candidate(b)
        c["asin"] = c["asin"] + f"-x{len(out)}"
        out.append(c)
    return out


_SYNTH_FIELDS = ("asin", "Title", "price", "rating", "num_reviews",
                 "Brand", "product_category", "query",
                 "BulletPoints", "Description", "Attributes", "options")


def _as_candidate(b):
    price = b.get("price", 0.0)
    try:
        price_float = float(str(price).replace("$", "").split(" to ")[0])
    except ValueError:
        price_float = 0.0
    return {"asin": b["asin"], "family": b.get("family", "?"),
            "kind": f"synthetic:{b.get('family', '?')}",
            "synthetic": True, "judge_score": b.get("judge_score", 0),
            "item": {k: b.get(k) for k in _SYNTH_FIELDS},
            "price_float": price_float,
            "reviews": b.get("reviews", [])}
